    "<!-- rqti's extended QTI 2.2 schema: QTI 2.2 plus the OPAL/ONYX and HTML",
    "     extensions that rqti exports. QTI 2.2 already allows data-* attributes,",
    "     download links, match table orientation and list types. Generated by",
    "     tools/build-qti22-extension.R from imsqti_v2p2.xsd; do not edit. -->",
    '<xs:schema xmlns="http://www.imsglobal.org/xsd/imsqti_v2p2"',
    '     targetNamespace="http://www.imsglobal.org/xsd/imsqti_v2p2"',
    '     xmlns:xi="http://www.w3.org/2001/XInclude"',
    '     xmlns:m2="http://www.w3.org/1998/Math/MathML"',
    '     xmlns:apip="http://www.imsglobal.org/xsd/apip/apipv1p0/imsapip_qtiv1p0"',
    '     xmlns:m3="http://www.w3.org/2010/Math/MathML"',
    '     xmlns:qh5="http://www.imsglobal.org/xsd/imsqtiv2p2_html5_v1p0"',
    '     xmlns:ssml11="http://www.w3.org/2010/10/synthesis"',
    '     xmlns:maptol="http://bps-system.de/xsd/imsqti_ext_maptolresponse"',
    '     xmlns:xs="http://www.w3.org/2001/XMLSchema"',
    '     elementFormDefault="qualified"',
    '     attributeFormDefault="unqualified">',
    '    <xs:import namespace="http://www.w3.org/XML/1998/namespace" schemaLocation="../w3/xml.xsd"/>',
    '    <xs:import namespace="http://www.w3.org/2001/XInclude" schemaLocation="../w3/XInclude.xsd"/>',
    '    <xs:import namespace="http://www.w3.org/1998/Math/MathML" schemaLocation="../w3/mathml2/mathml2.xsd"/>',
    '    <xs:import namespace="http://www.imsglobal.org/xsd/apip/apipv1p0/imsapip_qtiv1p0" schemaLocation="../apipv1p0/apipv1p0_qtiextv2p2_v1p0p1.xsd"/>',
    '    <xs:import namespace="http://www.w3.org/2010/Math/MathML" schemaLocation="../w3/mathml3/mathml3.xsd"/>',
    '    <xs:import namespace="http://www.imsglobal.org/xsd/imsqtiv2p2_html5_v1p0" schemaLocation="./imsqtiv2p2_html5_v1p0.xsd"/>',
    '    <xs:import namespace="http://www.w3.org/2010/10/synthesis" schemaLocation="../w3/ssml11/ssmlv1p1-core.xsd"/>',
    '    <xs:import namespace="http://bps-system.de/xsd/imsqti_ext_maptolresponse" schemaLocation="maptolresponse.xsd"/>',
    "",
    '    <xs:include schemaLocation="imsqti_v2p2.xsd"/>',
    "",
    redefine("OPAL/ONYX stores MAXIMA programs in an unqualified value attribute.",
             "CustomOperator.Type", FALSE,
             '<xs:attribute name="value" type="xs:string" use="optional"/>'),
    redefine(paste("OPAL reassigns correct answers before response rules. The required\n",
                   "        setCorrectResponse separates this extension from the base rule group."),
             "ResponseProcessing.Type", FALSE,
             c('<xs:sequence minOccurs="0">',
               '    <xs:element ref="setCorrectResponse" maxOccurs="unbounded"/>',
               '    <xs:choice minOccurs="0" maxOccurs="unbounded">',
               choice_body("ResponseProcessing.Type", 8),
               "    </xs:choice>",
               "</xs:sequence>")),
    "    <!-- details is HTML block content: allow it at any position in itemBody,",
    "         div (rqti wraps gap exercises in a div) and modalFeedback. A redefined",
    "         type can only append to its content, so each type appends",
    "         (details, content*)*; with the original content* this accepts details",
    "         anywhere after the first element. -->",
    details_redefine("ItemBody.Type", "ItemBody.Content", FALSE),
    details_redefine("Div.Type", "Div.Content", TRUE),
    details_redefine("ModalFeedback.Type", "ModalFeedback.Content", TRUE),
    redefine(paste("OPAL test settings (AssessmentTestOpal): downloadable files, and\n",
                   "        semicolon-separated features such as scientific-calculator."),
             "AssessmentTest.Type", FALSE,
             c('<xs:attribute name="data-downloads" type="xs:string" use="optional"/>',
               '<xs:attribute name="data-features" type="xs:string" use="optional"/>')),
    redefine(paste("OPAL recalculates variables and reshuffles choices for each item\n",
                   "        attempt when rebuildVariables is true (rebuild_variables in rqti)."),
             "ItemSessionControl.Type", FALSE,
             '<xs:attribute name="rebuildVariables" type="xs:boolean" use="optional"/>'),
    # setValue holds exactly one expression; OPAL's tolerant text gaps put
    # mapTolResponse in its place, so the redefinition repeats the expressions.
    "    <!-- OPAL's tolerant text gaps (TextGapOpal) set a value from mapTolResponse. -->",
    '    <xs:redefine schemaLocation="imsqti_v2p2.xsd">',
    '        <xs:complexType name="SetValue.Type" abstract="false" mixed="false">',
    "            <xs:complexContent>",
    '                <xs:restriction base="SetValue.Type">',
    "                    <xs:sequence>",
    '                        <xs:choice minOccurs="1" maxOccurs="1">',
    choice_body("SetValue.Type", 28),
    '                            <xs:element ref="maptol:mapTolResponse" minOccurs="1" maxOccurs="1"/>',
    "                        </xs:choice>",
    "                    </xs:sequence>",
    '                    <xs:attributeGroup ref="identifier.SetValue.Attr"/>',
    "                </xs:restriction>",
    "            </xs:complexContent>",
    "        </xs:complexType>",
    "    </xs:redefine>",
    "",
    "    <!-- Original content of ItemBody.Type, Div.Type and ModalFeedback.Type,",
    "         used after details by the redefinitions above. -->",
    group("ItemBody.Content", "ItemBody.Type"),
    group("Div.Content", "Div.Type"),
    group("ModalFeedback.Content", "ModalFeedback.Type"),
    "    <!-- details: an optional summary followed by the content of a div. -->",
    '    <xs:complexType name="Details.Type" mixed="true">',
    "        <xs:sequence>",
    '            <xs:element ref="summary" minOccurs="0" maxOccurs="1"/>',
    '            <xs:group ref="Div.Content" minOccurs="0" maxOccurs="unbounded"/>',
    "        </xs:sequence>",
    "    </xs:complexType>",
    "",
    '    <xs:element name="details" type="Details.Type"/>',
    '    <xs:element name="summary" type="HTMLText.Type"/>',
    "</xs:schema>")
schema <- unlist(strsplit(schema, "\n", fixed = TRUE))

if ("--check" %in% commandArgs(TRUE)) {
    if (!file.exists(output) || !identical(readLines(output), schema)) {
        stop("Extended QTI 2.2 schema is stale; run tools/build-qti22-extension.R",
             call. = FALSE)
    }
    cat("Extended QTI 2.2 schema matches its source.\n")
} else {
    writeLines(schema, output)
    cat("Wrote", sub(paste0(root, "/"), "", output), "\n")
}
