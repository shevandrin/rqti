#!/usr/bin/env Rscript
# Build or check rqti's extended QTI 2.2 schema, inst/schemas/qti_v2p2_extension.xsd.
#
#   Rscript tools/build-qti22-extension.R          # write the schema
#   Rscript tools/build-qti22-extension.R --check  # fail if it is stale
#
# The schema is QTI 2.2 plus the OPAL/ONYX and HTML extensions that rqti
# exports (the QTI 2.1 counterpart is inst/qti_v2p1p2_extension.xsd). Several
# extensions need the original content models of QTI 2.2 types, which this
# script copies from inst/xsd/imsqti_v2p2.xsd.

file_arg <- grep("^--file=", commandArgs(FALSE), value = TRUE)
root <- normalizePath(file.path(dirname(sub("^--file=", "", file_arg)), ".."))
base <- readLines(file.path(root, "inst", "xsd", "imsqti_v2p2.xsd"))
output <- file.path(root, "inst", "schemas", "qti_v2p2_extension.xsd")

type_lines <- function(type) {
    start <- grep(sprintf('complexType name="%s"', type), base, fixed = TRUE)
    stopifnot(length(start) == 1L)
    end <- start + grep("</xs:complexType>", base[start:length(base)], fixed = TRUE)[1] - 1
    base[start:end]
}

# Body of the first top-level choice of a type, re-indented.
choice_body <- function(type, indent) {
    lines <- type_lines(type)
    open <- grep("<xs:choice ", lines)[1]
    depth <- 0
    for (i in open:length(lines)) {
        depth <- depth + grepl("<xs:choice[ >]", lines[i]) - grepl("</xs:choice>", lines[i])
        if (depth == 0) {
            close <- i
            break
        }
    }
    body <- lines[(open + 1):(close - 1)]
    stopifnot(!any(grepl("annotation|documentation", body)))
    old <- nchar(sub("^( *).*", "\\1", body[1]))
    paste0(strrep(" ", indent), substring(body, old + 1))
}

group <- function(name, type) {
    c(sprintf('    <xs:group name="%s">', name), "        <xs:choice>",
      choice_body(type, 12), "        </xs:choice>", "    </xs:group>", "")
}

redefine <- function(comment, type, mixed, body) {
    c(paste0("    <!-- ", comment, " -->"),
      '    <xs:redefine schemaLocation="imsqti_v2p2.xsd">',
      sprintf('        <xs:complexType name="%s"%s>', type,
              if (mixed) ' mixed="true"' else ""),
      "            <xs:complexContent>",
      sprintf('                <xs:extension base="%s">', type),
      paste0("                    ", body),
      "                </xs:extension>",
      "            </xs:complexContent>",
      "        </xs:complexType>",
      "    </xs:redefine>", "")
}

details_redefine <- function(type, group, mixed) {
    redefine(sprintf("details anywhere in %s", sub(".Type", "", type, fixed = TRUE)),
             type, mixed,
             c('<xs:sequence minOccurs="0" maxOccurs="unbounded">',
               '    <xs:element ref="details"/>',
               sprintf('    <xs:group ref="%s" minOccurs="0" maxOccurs="unbounded"/>', group),
               "</xs:sequence>"))
}

schema <- c(
